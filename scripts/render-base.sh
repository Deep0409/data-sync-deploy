#!/usr/bin/env bash
# Renders the Helm chart with production values into the kustomize base.
#
# The production overlay uses this file as its base. Run it (make render)
# after any change to the chart or values. CI runs `make check-render` and
# fails if the committed file is out of date.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
chart="${root}/helm/charts/data-sync"
out="${root}/standard/data-sync/base/helm-output.yaml"
namespace="${NAMESPACE:-data-sync}"

# Same layering as a real install: defaults first, then the production file.
#
# Blank lines are stripped because Helm 4 puts one before every `---` and
# Helm 3 doesn't. Without this, the committed file depends on whose laptop
# rendered it and `make check-render` fails for no real reason. It's safe
# here because the manifests contain no multi-line YAML strings.
{
  echo "# Generated by scripts/render-base.sh, do not edit."
  helm template data-sync "${chart}" \
    --namespace "${namespace}" \
    -f "${chart}/values.yaml" \
    -f "${chart}/values.production.yaml" \
    | sed '/^$/d'
} > "${out}"

echo "wrote ${out}"
